/**
 *
 *                          📂 Buffer vs Stream 📂
 *
 *  📥 BUFFER:
 *  +---------------------------------------+
 *  |                Buffer                 |
 *  +---------------------------------------+
 *  | 🌊 Data is loaded entirely into memory |
 *  | 🐢 Suitable for small files            |
 *  | 💾 Can be inefficient for large files  |
 *  +---------------------------------------+
 *
 *  🚚 STREAM:
 *  +---------------------------------------+
 *  |                Stream                 |
 *  +---------------------------------------+
 *  | 🌊 Data is processed in chunks         |
 *  | 🐇 Suitable for large files            |
 *  | ⚡ Efficient, uses less memory         |
 *  +---------------------------------------+
 */
